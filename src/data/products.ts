export function formatProductPriceRange(product: Product): string {
  const fmt = (n: number) =>
    new Intl.NumberFormat('en-IN', {
      style: 'currency',
      currency: 'INR',
      maximumFractionDigits: 0,
    }).format(n);

  if (product.requestQuoteOnly) {
    return 'Request a Quote';
  }

  if (product.minPrice === product.maxPrice) {
    return `${fmt(product.minPrice)} ${product.pricingUnitLabel}`;
  }
  return `${fmt(product.minPrice)} – ${product.maxPrice.toLocaleString('en-IN')} ${product.pricingUnitLabel}`;
}
